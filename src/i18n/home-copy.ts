export function localizeCopy(value: string, locale: Locale, dictionary?: Record<string, string>) {
  if (dictionary && Object.prototype.hasOwnProperty.call(dictionary, value)) return dictionary[value];
  if (locale === "en") return value;
  return lookupSitePhrase(value, locale) ?? copy[value]?.[locale] ?? value;
}

export function localizeHome<T>(value: T, locale: Locale, dictionary?: Record<string, string>): T {
  if (locale === "en" && !dictionary) return value;
  if (typeof value === "string") return localizeCopy(value, locale, dictionary) as T;
  if (Array.isArray(value)) return value.map((item) => localizeHome(item, locale, dictionary)) as T;
  if (value && typeof value === "object") {
    const next: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value)) {
      next[key] =
        key === "href" || key === "id" || key === "imageUrl" || key === "placeId"
          ? item
          : localizeHome(item, locale, dictionary);
    }
    return next as T;
  }
  return value;
}
